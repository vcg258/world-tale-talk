CREATE TABLE deleted_worlds
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    name            VARCHAR(50)   NOT NULL,
    genre           VARCHAR(15)   NOT NULL,
    description     TEXT          NOT NULL,
    setting_text    TEXT          NOT NULL,
    target_turn     INTEGER       NOT NULL,
    rating_avg      DECIMAL(3, 2) NOT NULL,
    completed_count INTEGER       NOT NULL,
    abandoned_count INTEGER       NOT NULL,
    play_count      INTEGER       NOT NULL,
    CONSTRAINT pk_deleted_worlds PRIMARY KEY (id)
);

COMMENT ON TABLE deleted_worlds IS '삭제된 세계관 통계 스냅샷.';
