COMMENT ON COLUMN deleted_worlds.description IS '유저에게 보이던 카드 소개 텍스트';
COMMENT ON COLUMN deleted_worlds.setting_text IS 'LLM System Prompt 에 주입되던 세계관 설정집';
COMMENT ON COLUMN deleted_worlds.target_turn IS '메인 스토리 목표 턴 수';
COMMENT ON COLUMN deleted_worlds.rating_avg IS '삭제 시점 평균 평점';
COMMENT ON COLUMN deleted_worlds.completed_count IS '완결한 세션 수';
COMMENT ON COLUMN deleted_worlds.abandoned_count IS '중도포기한 세션 수';
